"""Describe database tables as ordinary Python classes.

SQLAlchemy calls these classes ORM models. The ORM (object-relational mapper)
translates between Python objects and rows in a relational database.
"""

# ``datetime`` stores a point in time; ``timezone`` lets us specify UTC rather
# than relying on whichever local time zone happens to run the server.
from datetime import datetime, timezone

# These SQLAlchemy types describe the underlying database column types.
from sqlalchemy import Boolean, DateTime, Integer, String, Text

# ``Mapped`` annotates a mapped Python attribute; ``mapped_column`` defines the
# database column and its rules.
from sqlalchemy.orm import Mapped, mapped_column

# Every model inherits Base so SQLAlchemy can collect its table definition.
from app.database import Base


class Task(Base):
    """One learning task, represented as one row in the ``tasks`` table."""

    # SQLAlchemy uses this name when creating and querying the database table.
    __tablename__ = "tasks"

    # ``Mapped[int]`` says Python code sees an integer ID. The primary key is
    # unique and is generated by the database for each new row.
    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    # Store a required title as text with a 200-character database limit.
    title: Mapped[str] = mapped_column(String(200), nullable=False)

    # ``str | None`` means the description may be text or Python None.
    # ``nullable=True`` allows the matching database value to be SQL NULL.
    description: Mapped[str | None] = mapped_column(Text, nullable=True)

    # New tasks start unfinished. ``nullable=False`` means the table must
    # always hold either True or False, never a missing value.
    completed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Record the creation time. The default is a function (lambda), so the
    # current UTC time is calculated separately each time a task is created.
    created_at: Mapped[datetime] = mapped_column(
        # Ask the database to store a date and time intended to include a zone.
        DateTime(timezone=True),
        # SQLAlchemy calls this function when no created_at value is supplied.
        default=lambda: datetime.now(timezone.utc),
        # Every task is expected to have a creation time.
        nullable=False,
    )
